import streamlit as st
import pandas as pd
import pickle
import matplotlib.pyplot as plt
import datetime  # NEW


with open("house_price_pipe.pkl", "rb") as f:
    model = pickle.load(f)

st.set_page_config(page_title="House Price Predictor", layout="wide")


tab1, tab2, tab3 = st.tabs(["🏠 Prediction", "📊 Model info", "🔍 Feature importance"])


with tab1:
    st.title("Estimate house price")

    st.write(
        "Fill in the details of the property below and the model will "
        "estimate a selling price."
    )

    col1, col2 = st.columns(2)

    with col1:
        MSSubClass = st.number_input("MSSubClass", min_value=20, max_value=200, value=60)
        LotArea = st.number_input("Lot area (sq ft)", min_value=1000, max_value=50000, value=8000)
        OverallCond = st.slider("Overall condition (1–10)", 1, 10, 5)
        YearBuilt = st.number_input("Year built", min_value=1800, max_value=2025, value=2000)
        BsmtFinSF2 = st.number_input("Finished basement (SF2)", min_value=0, max_value=2000, value=0)

    with col2:
        MSZoning = st.selectbox("Zoning (MSZoning)", ["RL", "RM", "C", "FV", "RH"])
        LotConfig = st.selectbox("Lot configuration", ["Inside", "Corner", "FR2", "FR3", "CulDSac"])
        BldgType = st.selectbox("Building type", ["1Fam", "2fmCon", "Duplex", "TwnhsE", "Twnhs"])
        YearRemodAdd = st.number_input("Year remodeled", min_value=1800, max_value=2025, value=2005)
        Exterior1st = st.selectbox(
            "Exterior finish (Exterior1st)",
            ["VinylSd", "MetalSd", "Wd Sdng", "HdBoard", "Stucco"],
        )
        TotalBsmtSF = st.number_input("Total basement area (sq ft)", min_value=0, max_value=3000, value=800)

    input_data = {
        "MSSubClass": MSSubClass,
        "MSZoning": MSZoning,
        "LotArea": LotArea,
        "LotConfig": LotConfig,
        "BldgType": BldgType,
        "OverallCond": OverallCond,
        "YearBuilt": YearBuilt,
        "YearRemodAdd": YearRemodAdd,
        "Exterior1st": Exterior1st,
        "BsmtFinSF2": BsmtFinSF2,
        "TotalBsmtSF": TotalBsmtSF,
    }

    input_df = pd.DataFrame([input_data])

    current_year = datetime.datetime.now().year

    input_df["HouseAge"] = current_year - input_df["YearBuilt"]
    input_df["YearsSinceRemod"] = current_year - input_df["YearRemodAdd"]

    input_df["BsmtFinRatio"] = input_df["BsmtFinSF2"] / input_df["TotalBsmtSF"]
    input_df["BsmtFinRatio"] = input_df["BsmtFinRatio"].fillna(0)

    input_df["TotalLivingArea"] = input_df["TotalBsmtSF"] + input_df["BsmtFinSF2"]

    input_df["IsRemodeled"] = (input_df["YearBuilt"] != input_df["YearRemodAdd"]).astype(int)

    # Use fixed bins but same labels as training
    input_df["LotAreaCategory"] = pd.cut(
        input_df["LotArea"],
        bins=[0, 5000, 10000, 15000, 1e9],
        labels=["Small", "Medium", "Large", "XL"],
        include_lowest=True,
    ).astype(str)

    if st.button("Predict price"):
        price = model.predict(input_df)[0]
        st.success(f"Estimated price: ${price:,.0f}")

        st.caption(
            "Prediction generated by a Random Forest model trained on house "
            "sale data with preprocessing inside a scikit-learn pipeline."
        )


with tab2:
    st.header("Model details")

    st.subheader("Model")
    st.write("• RandomForestRegressor wrapped in a scikit-learn Pipeline.")

    st.subheader("Training setup")
    st.write(
        "- 5-fold cross-validation\n"
        "- Feature engineering + one-hot encoding + scaling handled inside the pipeline\n"
        "- Same preprocessing is applied during training and prediction"
    )

    st.subheader("Input features")
    st.write("These are the raw features the pipeline expects before preprocessing:")
    st.json(list(model.feature_names_in_))

    st.subheader("Why this model?")
    st.write(
        "- Can model non-linear relationships\n"
        "- Works well with mixed numeric and categorical features\n"
        "- Robust to outliers\n"
        "- Provides feature importance for interpretation"
    )


with tab3:
    st.header("Feature importance")

    st.write(
        "The chart below shows which features contributed the most to the "
        "model during training."
    )

    try:
        fi = pd.read_csv("feature_importance.csv")
        st.dataframe(fi)

        fig, ax = plt.subplots(figsize=(8, 5))
        ax.barh(fi["feature"], fi["importance"])
        ax.invert_yaxis()
        ax.set_xlabel("Importance")
        ax.set_title("Top 20 most important features")
        st.pyplot(fig)

    except FileNotFoundError:
        st.warning(
            "Could not find 'feature_importance.csv'. "
            "Run the training notebook to generate it before using this tab."
        )
